#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ReplaySourceCandidate {
    pub gpu_identity: Option<CaptureGpuIdentity>,
    pub width: u32,
    pub height: u32,
    pub pixel_format: ReplayPixelFormat,
    pub target_frames_per_second: u8,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum ReplaySourceRejection {
    InvalidStructure = 1,
    ProtectedSwapchain = 2,
    ArrayLayersUnsupported = 3,
    TransferSourceUsageMissing = 4,
    DimensionsUnsupported = 5,
    PixelFormatUnsupported = 6,
    ExternalMemoryUnsupported = 7,
    EncoderBackendUnavailable = 8,
    VideoEncodeUnsupported = 9,
    GpuIdentityUnavailable = 10,
}

impl ReplaySourceRejection {
    fn from_wire(value: u8) -> Result<Self, ProtocolError> {
        match value {
            1 => Ok(Self::InvalidStructure),
            2 => Ok(Self::ProtectedSwapchain),
            3 => Ok(Self::ArrayLayersUnsupported),
            4 => Ok(Self::TransferSourceUsageMissing),
            5 => Ok(Self::DimensionsUnsupported),
            6 => Ok(Self::PixelFormatUnsupported),
            7 => Ok(Self::ExternalMemoryUnsupported),
            8 => Ok(Self::EncoderBackendUnavailable),
            9 => Ok(Self::VideoEncodeUnsupported),
            10 => Ok(Self::GpuIdentityUnavailable),
            _ => Err(ProtocolError::new(
                "replay source rejection reason is unsupported",
            )),
        }
    }
}

impl ReplaySourceCandidate {
    fn validate(self) -> Result<(), ProtocolError> {
        if !replay_source_dimensions_supported(self.width, self.height) {
            return Err(ProtocolError::new("replay source dimensions are invalid"));
        }
        if !matches!(self.target_frames_per_second, 30 | 60 | 120) {
            return Err(ProtocolError::new("replay source frame rate is invalid"));
        }
        Ok(())
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum CaptureMessage {
    /// Identity of the currently presenting device; independent of Replay.
    GpuIdentity {
        session_id: CaptureSessionId,
        api: CaptureApi,
        identity: Option<CaptureGpuIdentity>,
    },
    Hello {
        session_id: CaptureSessionId,
        process_id: u32,
        api: CaptureApi,
        producer_started_monotonic_ns: u64,
    },
    FrameBatch {
        session_id: CaptureSessionId,
        api: CaptureApi,
        first_sequence: u64,
        frame_intervals_ns: Vec<u64>,
    },
    Goodbye {
        session_id: CaptureSessionId,
        api: CaptureApi,
        last_sequence: u64,
        reason: GoodbyeReason,
    },
    /// Metadata-only candidate. Raw pixels and encoded packets are forbidden
    /// from this bounded datagram protocol.
    ReplaySourceCandidate {
        session_id: CaptureSessionId,
        candidate: ReplaySourceCandidate,
    },
    ReplaySourceRejected {
        session_id: CaptureSessionId,
        reason: ReplaySourceRejection,
    },
    /// Bounded proof that one swapchain image reached Redunar-owned mapped
    /// memory. Pixel bytes never enter this datagram protocol.
    ReplayFrameCopied {
        session_id: CaptureSessionId,
        sequence: u64,
        source: ReplaySourceCandidate,
        copied_bytes: u32,
        sample_checksum: u64,
    },
    /// Metadata for one GPU-backed exported frame. The FD number is meaningful
    /// only in the producer process identified by `Hello`; no pixels cross
    /// this datagram protocol.
    ReplayFrameExported {
        session_id: CaptureSessionId,
        sequence: u64,
        fd_number: u32,
        source: ReplaySourceCandidate,
        offset: u32,
        stride: u32,
        modifier: u64,
        timestamp_ns: u64,
        duration_ns: u64,
    },
    /// Daemon-to-producer release token. It permits a producer-side export
    /// slot to be reused only after the daemon has finished importing it.
    ReplayFrameReleased {
        session_id: CaptureSessionId,
        sequence: u64,
    },
    OverlayStatus {
        session_id: CaptureSessionId,
        status: OverlayRuntimeStatus,
    },
}

impl CaptureMessage {
    #[must_use]
    pub const fn session_id(&self) -> CaptureSessionId {
        match self {
            Self::GpuIdentity { session_id, .. }
            | Self::Hello { session_id, .. }
            | Self::FrameBatch { session_id, .. }
            | Self::Goodbye { session_id, .. }
            | Self::ReplaySourceCandidate { session_id, .. }
            | Self::ReplaySourceRejected { session_id, .. }
            | Self::ReplayFrameCopied { session_id, .. }
            | Self::ReplayFrameExported { session_id, .. }
            | Self::ReplayFrameReleased { session_id, .. }
            | Self::OverlayStatus { session_id, .. } => *session_id,
        }
    }
}

/// Encode one message into caller-owned storage so capture producers do not
/// need to allocate on the presentation path.
///
/// # Errors
///
/// Returns [`ProtocolError`] for invalid frame batches or insufficient output
/// storage.
pub fn encode_message(message: &CaptureMessage, output: &mut [u8]) -> Result<usize, ProtocolError> {
    let (kind, payload_bytes) = message_layout(message)?;
    let message_bytes = HEADER_BYTES + payload_bytes;
    if message_bytes > MAX_MESSAGE_BYTES {
        return Err(ProtocolError::new("capture message exceeds protocol limit"));
    }
    if output.len() < message_bytes {
        return Err(ProtocolError::new("capture output buffer is too small"));
    }

    output[..message_bytes].fill(0);
    output[..8].copy_from_slice(&MAGIC);
    write_u16(output, 8, PROTOCOL_VERSION);
    output[10] = kind;
    let payload_bytes = u16::try_from(payload_bytes)
        .map_err(|_| ProtocolError::new("capture payload length exceeds wire field"))?;
    write_u16(output, 12, payload_bytes);
    output[16..32].copy_from_slice(&message.session_id().as_bytes());

    encode_payload(message, output)?;
    Ok(message_bytes)
}

fn message_layout(message: &CaptureMessage) -> Result<(u8, usize), ProtocolError> {
    let layout = match message {
        CaptureMessage::GpuIdentity { .. } => (KIND_GPU_IDENTITY, GPU_IDENTITY_BYTES),
        CaptureMessage::Hello { .. } => (KIND_HELLO, HELLO_BYTES),
        CaptureMessage::FrameBatch {
            frame_intervals_ns, ..
        } => {
            validate_intervals(frame_intervals_ns)?;
            (
                KIND_FRAME_BATCH,
                FRAME_BATCH_PREFIX_BYTES + frame_intervals_ns.len() * 8,
            )
        }
        CaptureMessage::Goodbye { .. } => (KIND_GOODBYE, GOODBYE_BYTES),
        CaptureMessage::ReplaySourceCandidate { candidate, .. } => {
            candidate.validate()?;
            (KIND_REPLAY_SOURCE_CANDIDATE, REPLAY_SOURCE_CANDIDATE_BYTES)
        }
        CaptureMessage::ReplaySourceRejected { .. } => {
            (KIND_REPLAY_SOURCE_REJECTED, REPLAY_SOURCE_REJECTED_BYTES)
        }
        CaptureMessage::ReplayFrameCopied {
            source,
            copied_bytes,
            ..
        } => {
            source.validate()?;
            validate_copied_bytes(*source, *copied_bytes)?;
            (KIND_REPLAY_FRAME_COPIED, REPLAY_FRAME_COPIED_BYTES)
        }
        CaptureMessage::ReplayFrameExported {
            fd_number,
            source,
            offset,
            stride,
            modifier: _,
            timestamp_ns,
            duration_ns,
            ..
        } => {
            source.validate()?;
            validate_exported_frame(*fd_number, *offset, *stride, *timestamp_ns, *duration_ns)?;
            (KIND_REPLAY_FRAME_EXPORTED, REPLAY_FRAME_EXPORTED_BYTES)
        }
        CaptureMessage::ReplayFrameReleased { .. } => {
            (KIND_REPLAY_FRAME_RELEASED, REPLAY_FRAME_RELEASED_BYTES)
        }
        CaptureMessage::OverlayStatus { .. } => (KIND_OVERLAY_STATUS, OVERLAY_STATUS_BYTES),
    };
    Ok(layout)
}

fn encode_payload(message: &CaptureMessage, output: &mut [u8]) -> Result<(), ProtocolError> {
    match message {
        CaptureMessage::GpuIdentity { identity, api, .. } => {
            encode_gpu_identity(output, *api, *identity);
        }
        CaptureMessage::Hello {
            process_id,
            api,
            producer_started_monotonic_ns,
            ..
        } => {
            write_u32(output, HEADER_BYTES, *process_id);
            output[HEADER_BYTES + 4] = *api as u8;
            write_u64(output, HEADER_BYTES + 8, *producer_started_monotonic_ns);
        }
        CaptureMessage::FrameBatch {
            api,
            first_sequence,
            frame_intervals_ns,
            ..
        } => {
            write_u64(output, HEADER_BYTES, *first_sequence);
            let frame_count = u16::try_from(frame_intervals_ns.len())
                .map_err(|_| ProtocolError::new("capture frame count exceeds wire field"))?;
            write_u16(output, HEADER_BYTES + 8, frame_count);
            output[HEADER_BYTES + 10] = *api as u8;
            for (index, interval) in frame_intervals_ns.iter().enumerate() {
                write_u64(
                    output,
                    HEADER_BYTES + FRAME_BATCH_PREFIX_BYTES + index * 8,
                    *interval,
                );
            }
        }
        CaptureMessage::Goodbye {
            api,
            last_sequence,
            reason,
            ..
        } => {
            write_u64(output, HEADER_BYTES, *last_sequence);
            output[HEADER_BYTES + 8] = *reason as u8;
            output[HEADER_BYTES + 9] = *api as u8;
        }
        CaptureMessage::ReplaySourceCandidate { candidate, .. } => {
            encode_replay_source_candidate(output, *candidate);
        }
        CaptureMessage::ReplaySourceRejected { reason, .. } => {
            output[HEADER_BYTES] = *reason as u8;
        }
        CaptureMessage::ReplayFrameCopied {
            sequence,
            source,
            copied_bytes,
            sample_checksum,
            ..
        } => {
            encode_replay_frame_copied(output, *sequence, *source, *copied_bytes, *sample_checksum);
        }
        CaptureMessage::ReplayFrameExported {
            sequence,
            fd_number,
            source,
            offset,
            stride,
            modifier,
            timestamp_ns,
            duration_ns,
            ..
        } => {
            let base = HEADER_BYTES;
            write_u64(output, base, *sequence);
            write_u32(output, base + 8, *fd_number);
            write_u32(output, base + 12, source.width);
            write_u32(output, base + 16, source.height);
            output[base + 20] = source.pixel_format as u8;
            output[base + 21] = source.target_frames_per_second;
            write_u32(output, base + 24, *offset);
            write_u32(output, base + 28, *stride);
            write_u64(output, base + 32, *modifier);
            write_u64(output, base + 40, *timestamp_ns);
            // Duration is carried in the fixed trailing field by reusing the
            // message's reserved extension area in protocol v5.
            write_u64(output, base + 48, *duration_ns);
            gpu_identity::encode(source.gpu_identity, &mut output[base + 56..]);
        }
        CaptureMessage::ReplayFrameReleased { sequence, .. } => {
            write_u64(output, HEADER_BYTES, *sequence);
        }
        CaptureMessage::OverlayStatus { status, .. } => {
            let (state, reason) = match status {
                OverlayRuntimeStatus::Requested => (1, 0),
                OverlayRuntimeStatus::Active => (2, 0),
                OverlayRuntimeStatus::Error(reason) => (3, *reason as u8),
            };
            output[HEADER_BYTES] = state;
            output[HEADER_BYTES + 1] = reason;
        }
    }
    Ok(())
}

fn encode_gpu_identity(output: &mut [u8], api: CaptureApi, identity: Option<CaptureGpuIdentity>) {
    gpu_identity::encode(identity, &mut output[HEADER_BYTES..]);
    output[HEADER_BYTES + 40] = api as u8;
}

fn encode_replay_source_candidate(output: &mut [u8], candidate: ReplaySourceCandidate) {
    write_u32(output, HEADER_BYTES, candidate.width);
    write_u32(output, HEADER_BYTES + 4, candidate.height);
    output[HEADER_BYTES + 8] = candidate.pixel_format as u8;
    output[HEADER_BYTES + 9] = candidate.target_frames_per_second;
    gpu_identity::encode(candidate.gpu_identity, &mut output[HEADER_BYTES + 16..]);
}

fn encode_replay_frame_copied(
    output: &mut [u8],
    sequence: u64,
    source: ReplaySourceCandidate,
    copied_bytes: u32,
    sample_checksum: u64,
) {
    write_u64(output, HEADER_BYTES, sequence);
    write_u32(output, HEADER_BYTES + 8, copied_bytes);
    write_u32(output, HEADER_BYTES + 12, source.width);
    write_u32(output, HEADER_BYTES + 16, source.height);
    output[HEADER_BYTES + 20] = source.pixel_format as u8;
    output[HEADER_BYTES + 21] = source.target_frames_per_second;
    write_u64(output, HEADER_BYTES + 24, sample_checksum);
    gpu_identity::encode(source.gpu_identity, &mut output[HEADER_BYTES + 32..]);
}

/// Encode a frame batch directly from a borrowed slice. Capture layers use
/// this form to avoid allocating a `Vec` when a fixed producer buffer fills.
///
/// # Errors
///
/// Returns [`ProtocolError`] for an empty/oversized/zero-valued batch or an
/// insufficient output buffer.
pub fn encode_frame_batch(
    session_id: CaptureSessionId,
    api: CaptureApi,
    first_sequence: u64,
    frame_intervals_ns: &[u64],
    output: &mut [u8],
) -> Result<usize, ProtocolError> {
    validate_intervals(frame_intervals_ns)?;
    let payload_bytes = FRAME_BATCH_PREFIX_BYTES + frame_intervals_ns.len() * 8;
    let message_bytes = HEADER_BYTES + payload_bytes;
    if output.len() < message_bytes {
        return Err(ProtocolError::new("capture output buffer is too small"));
    }

    output[..message_bytes].fill(0);
    output[..8].copy_from_slice(&MAGIC);
    write_u16(output, 8, PROTOCOL_VERSION);
    output[10] = KIND_FRAME_BATCH;
    let payload_bytes = u16::try_from(payload_bytes)
        .map_err(|_| ProtocolError::new("capture payload length exceeds wire field"))?;
    let frame_count = u16::try_from(frame_intervals_ns.len())
        .map_err(|_| ProtocolError::new("capture frame count exceeds wire field"))?;
    write_u16(output, 12, payload_bytes);
    output[16..32].copy_from_slice(&session_id.as_bytes());
    write_u64(output, HEADER_BYTES, first_sequence);
    write_u16(output, HEADER_BYTES + 8, frame_count);
    output[HEADER_BYTES + 10] = api as u8;
    for (index, interval) in frame_intervals_ns.iter().enumerate() {
        write_u64(
            output,
            HEADER_BYTES + FRAME_BATCH_PREFIX_BYTES + index * 8,
            *interval,
        );
    }
    Ok(message_bytes)
}

/// Decode one complete local capture message.
///
/// # Errors
///
/// Returns [`ProtocolError`] when the message is truncated, oversized,
/// unsupported, non-canonical, or contains invalid frame intervals.
pub fn decode_message(input: &[u8]) -> Result<CaptureMessage, ProtocolError> {
    let (kind, payload_bytes, session_id) = decode_header(input)?;

    match kind {
        KIND_GPU_IDENTITY if payload_bytes == GPU_IDENTITY_BYTES => {
            if input[HEADER_BYTES + 41..].iter().any(|byte| *byte != 0) {
                return Err(ProtocolError::new(
                    "capture GPU message reserved fields are non-zero",
                ));
            }
            Ok(CaptureMessage::GpuIdentity {
                session_id,
                api: CaptureApi::from_wire(input[HEADER_BYTES + 40])?,
                identity: gpu_identity::decode(&input[HEADER_BYTES..])?,
            })
        }
        KIND_HELLO if payload_bytes == HELLO_BYTES => Ok(CaptureMessage::Hello {
            session_id,
            process_id: read_u32(input, HEADER_BYTES),
            api: CaptureApi::from_wire(input[HEADER_BYTES + 4])?,
            producer_started_monotonic_ns: read_u64(input, HEADER_BYTES + 8),
        }),
        KIND_FRAME_BATCH if payload_bytes >= FRAME_BATCH_PREFIX_BYTES => {
            decode_frame_batch(input, session_id, payload_bytes)
        }
        KIND_GOODBYE if payload_bytes == GOODBYE_BYTES => decode_goodbye(input, session_id),
        KIND_REPLAY_SOURCE_CANDIDATE if payload_bytes == REPLAY_SOURCE_CANDIDATE_BYTES => {
            decode_replay_source_candidate(input, session_id)
        }
        KIND_REPLAY_SOURCE_REJECTED if payload_bytes == REPLAY_SOURCE_REJECTED_BYTES => {
            decode_replay_source_rejection(input, session_id)
        }
        KIND_REPLAY_FRAME_COPIED if payload_bytes == REPLAY_FRAME_COPIED_BYTES => {
            decode_replay_frame_copied(input, session_id)
        }
        KIND_REPLAY_FRAME_EXPORTED if payload_bytes == REPLAY_FRAME_EXPORTED_BYTES => {
            decode_replay_frame_exported(input, session_id)
        }
        KIND_REPLAY_FRAME_RELEASED if payload_bytes == REPLAY_FRAME_RELEASED_BYTES => {
            if input[HEADER_BYTES + 8..HEADER_BYTES + REPLAY_FRAME_RELEASED_BYTES]
                .iter()
                .any(|byte| *byte != 0)
            {
                return Err(ProtocolError::new(
                    "replay frame release reserved fields are non-zero",
                ));
            }
            Ok(CaptureMessage::ReplayFrameReleased {
                session_id,
                sequence: read_u64(input, HEADER_BYTES),
            })
        }
        KIND_OVERLAY_STATUS if payload_bytes == OVERLAY_STATUS_BYTES => {
            decode_overlay_status(input, session_id)
        }
        KIND_GPU_IDENTITY
        | KIND_HELLO
        | KIND_FRAME_BATCH
        | KIND_GOODBYE
        | KIND_REPLAY_SOURCE_CANDIDATE
        | KIND_REPLAY_SOURCE_REJECTED
        | KIND_REPLAY_FRAME_COPIED
        | KIND_REPLAY_FRAME_EXPORTED
        | KIND_REPLAY_FRAME_RELEASED
        | KIND_OVERLAY_STATUS => Err(ProtocolError::new(
            "capture message payload has invalid size",
        )),
        _ => Err(ProtocolError::new("capture message kind is unsupported")),
    }
}

fn decode_header(input: &[u8]) -> Result<(u8, usize, CaptureSessionId), ProtocolError> {
    if input.len() < HEADER_BYTES {
        return Err(ProtocolError::new("capture message is truncated"));
    }
    if input.len() > MAX_MESSAGE_BYTES {
        return Err(ProtocolError::new("capture message exceeds protocol limit"));
    }
    if input[..8] != MAGIC {
        return Err(ProtocolError::new("capture message has invalid magic"));
    }
    if read_u16(input, 8) != PROTOCOL_VERSION {
        return Err(ProtocolError::new(
            "capture protocol version is unsupported",
        ));
    }
    if input[11] != 0 || read_u16(input, 14) != 0 {
        return Err(ProtocolError::new(
            "capture message reserved fields are non-zero",
        ));
    }
    let payload_bytes = usize::from(read_u16(input, 12));
    if input.len() != HEADER_BYTES + payload_bytes {
        return Err(ProtocolError::new(
            "capture message length does not match header",
        ));
    }
    let mut session_bytes = [0; 16];
    session_bytes.copy_from_slice(&input[16..32]);
    let session_id = CaptureSessionId::new(session_bytes)?;
    Ok((input[10], payload_bytes, session_id))
}

fn decode_frame_batch(
    input: &[u8],
    session_id: CaptureSessionId,
    payload_bytes: usize,
) -> Result<CaptureMessage, ProtocolError> {
    if input[HEADER_BYTES + 11..HEADER_BYTES + FRAME_BATCH_PREFIX_BYTES]
        .iter()
        .any(|byte| *byte != 0)
    {
        return Err(ProtocolError::new(
            "capture frame batch reserved fields are non-zero",
        ));
    }
    let count = usize::from(read_u16(input, HEADER_BYTES + 8));
    if payload_bytes != FRAME_BATCH_PREFIX_BYTES + count * 8 {
        return Err(ProtocolError::new(
            "capture frame batch count does not match payload",
        ));
    }
    let mut intervals = Vec::with_capacity(count);
    for index in 0..count {
        intervals.push(read_u64(
            input,
            HEADER_BYTES + FRAME_BATCH_PREFIX_BYTES + index * 8,
        ));
    }
    validate_intervals(&intervals)?;
    Ok(CaptureMessage::FrameBatch {
        session_id,
        api: CaptureApi::from_wire(input[HEADER_BYTES + 10])?,
        first_sequence: read_u64(input, HEADER_BYTES),
        frame_intervals_ns: intervals,
    })
}

fn decode_goodbye(
    input: &[u8],
    session_id: CaptureSessionId,
) -> Result<CaptureMessage, ProtocolError> {
    if input[HEADER_BYTES + 10..HEADER_BYTES + GOODBYE_BYTES]
        .iter()
        .any(|byte| *byte != 0)
    {
        return Err(ProtocolError::new(
            "capture goodbye reserved fields are non-zero",
        ));
    }
    Ok(CaptureMessage::Goodbye {
        session_id,
        api: CaptureApi::from_wire(input[HEADER_BYTES + 9])?,
        last_sequence: read_u64(input, HEADER_BYTES),
        reason: GoodbyeReason::from_wire(input[HEADER_BYTES + 8])?,
    })
}

fn decode_overlay_status(
    input: &[u8],
    session_id: CaptureSessionId,
) -> Result<CaptureMessage, ProtocolError> {
    if input[HEADER_BYTES + 2..HEADER_BYTES + OVERLAY_STATUS_BYTES]
        .iter()
        .any(|byte| *byte != 0)
    {
        return Err(ProtocolError::new(
            "overlay status reserved fields are non-zero",
        ));
    }
    let status = match (input[HEADER_BYTES], input[HEADER_BYTES + 1]) {
        (1, 0) => OverlayRuntimeStatus::Requested,
        (2, 0) => OverlayRuntimeStatus::Active,
        (3, reason) => OverlayRuntimeStatus::Error(OverlayFailureReason::from_wire(reason)?),
        _ => return Err(ProtocolError::new("overlay status is invalid")),
    };
    Ok(CaptureMessage::OverlayStatus { session_id, status })
}

fn decode_replay_frame_copied(
    input: &[u8],
    session_id: CaptureSessionId,
) -> Result<CaptureMessage, ProtocolError> {
    if input[HEADER_BYTES + 22..HEADER_BYTES + 24]
        .iter()
        .any(|byte| *byte != 0)
    {
        return Err(ProtocolError::new(
            "replay frame copy reserved fields are non-zero",
        ));
    }
    let copied_bytes = read_u32(input, HEADER_BYTES + 8);
    let source = ReplaySourceCandidate {
        gpu_identity: gpu_identity::decode(&input[HEADER_BYTES + 32..])?,
        width: read_u32(input, HEADER_BYTES + 12),
        height: read_u32(input, HEADER_BYTES + 16),
        pixel_format: ReplayPixelFormat::from_wire(input[HEADER_BYTES + 20])?,
        target_frames_per_second: input[HEADER_BYTES + 21],
    };
    source.validate()?;
    validate_copied_bytes(source, copied_bytes)?;
    Ok(CaptureMessage::ReplayFrameCopied {
        session_id,
        sequence: read_u64(input, HEADER_BYTES),
        source,
        copied_bytes,
        sample_checksum: read_u64(input, HEADER_BYTES + 24),
    })
}

fn decode_replay_frame_exported(
    input: &[u8],
    session_id: CaptureSessionId,
) -> Result<CaptureMessage, ProtocolError> {
    let base = HEADER_BYTES;
    if input[base + 22..base + 24].iter().any(|byte| *byte != 0) {
        return Err(ProtocolError::new(
            "replay frame export reserved fields are non-zero",
        ));
    }
    let source = ReplaySourceCandidate {
        gpu_identity: gpu_identity::decode(&input[HEADER_BYTES + 56..])?,
        width: read_u32(input, base + 12),
        height: read_u32(input, base + 16),
        pixel_format: ReplayPixelFormat::from_wire(input[base + 20])?,
        target_frames_per_second: input[base + 21],
    };
    let fd_number = read_u32(input, base + 8);
    let offset = read_u32(input, base + 24);
    let stride = read_u32(input, base + 28);
    let modifier = read_u64(input, base + 32);
    let timestamp_ns = read_u64(input, base + 40);
    let duration_ns = read_u64(input, base + 48);
    source.validate()?;
    validate_exported_frame(fd_number, offset, stride, timestamp_ns, duration_ns)?;
    Ok(CaptureMessage::ReplayFrameExported {
        session_id,
        sequence: read_u64(input, base),
        fd_number,
        source,
        offset,
        stride,
        modifier,
        timestamp_ns,
        duration_ns,
    })
}

fn validate_exported_frame(
    fd_number: u32,
    offset: u32,
    stride: u32,
    timestamp_ns: u64,
    duration_ns: u64,
) -> Result<(), ProtocolError> {
    if !(3..=1_000_000).contains(&fd_number) {
        return Err(ProtocolError::new("replay export FD number is invalid"));
    }
    if stride == 0 || stride > MAX_REPLAY_SOURCE_WIDTH.saturating_mul(4) {
        return Err(ProtocolError::new("replay export stride is invalid"));
    }
    if duration_ns == 0 || duration_ns > 1_000_000_000 {
        return Err(ProtocolError::new("replay export duration is invalid"));
    }
    if timestamp_ns.checked_add(duration_ns).is_none() {
        return Err(ProtocolError::new("replay export timestamp overflows"));
    }
    let _ = offset;
    Ok(())
}

fn validate_copied_bytes(
    source: ReplaySourceCandidate,
    copied_bytes: u32,
) -> Result<(), ProtocolError> {
    let expected = source
        .width
        .checked_mul(source.height)
        .and_then(|pixels| pixels.checked_mul(4))
        .ok_or_else(|| ProtocolError::new("replay copied byte count overflowed"))?;
    if copied_bytes != expected {
        return Err(ProtocolError::new(
            "replay copied byte count does not match its source",
        ));
    }
    Ok(())
}

fn decode_replay_source_rejection(
    input: &[u8],
    session_id: CaptureSessionId,
) -> Result<CaptureMessage, ProtocolError> {
    if input[HEADER_BYTES + 1..HEADER_BYTES + REPLAY_SOURCE_REJECTED_BYTES]
        .iter()
        .any(|byte| *byte != 0)
    {
        return Err(ProtocolError::new(
            "replay source rejection reserved fields are non-zero",
        ));
    }
    Ok(CaptureMessage::ReplaySourceRejected {
        session_id,
        reason: ReplaySourceRejection::from_wire(input[HEADER_BYTES])?,
    })
}

fn decode_replay_source_candidate(
    input: &[u8],
    session_id: CaptureSessionId,
) -> Result<CaptureMessage, ProtocolError> {
    if input[HEADER_BYTES + 10..HEADER_BYTES + 16]
        .iter()
        .any(|byte| *byte != 0)
    {
        return Err(ProtocolError::new(
            "replay source reserved fields are non-zero",
        ));
    }
    let candidate = ReplaySourceCandidate {
        gpu_identity: gpu_identity::decode(&input[HEADER_BYTES + 16..])?,
        width: read_u32(input, HEADER_BYTES),
        height: read_u32(input, HEADER_BYTES + 4),
        pixel_format: ReplayPixelFormat::from_wire(input[HEADER_BYTES + 8])?,
        target_frames_per_second: input[HEADER_BYTES + 9],
    };
    candidate.validate()?;
    Ok(CaptureMessage::ReplaySourceCandidate {
        session_id,
        candidate,
    })
}

fn validate_intervals(intervals: &[u64]) -> Result<(), ProtocolError> {
    if intervals.is_empty() {
        return Err(ProtocolError::new("capture frame batch cannot be empty"));
    }
    if intervals.len() > MAX_FRAME_INTERVALS {
        return Err(ProtocolError::new(
            "capture frame batch exceeds protocol limit",
        ));
    }
    if intervals.contains(&0) {
        return Err(ProtocolError::new(
            "capture frame intervals must be greater than zero",
        ));
    }
    Ok(())
}

fn decode_hex(value: u8) -> Result<u8, ProtocolError> {
    match value {
        b'0'..=b'9' => Ok(value - b'0'),
        b'a'..=b'f' => Ok(value - b'a' + 10),
        _ => Err(ProtocolError::new(
            "capture session id is not canonical lowercase hex",
        )),
    }
}

fn write_u16(output: &mut [u8], offset: usize, value: u16) {
    output[offset..offset + 2].copy_from_slice(&value.to_le_bytes());
}

fn write_u32(output: &mut [u8], offset: usize, value: u32) {
    output[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
}

fn write_u64(output: &mut [u8], offset: usize, value: u64) {
    output[offset..offset + 8].copy_from_slice(&value.to_le_bytes());
}

fn read_u16(input: &[u8], offset: usize) -> u16 {
    u16::from_le_bytes(input[offset..offset + 2].try_into().expect("validated u16"))
}

fn read_u32(input: &[u8], offset: usize) -> u32 {
    u32::from_le_bytes(input[offset..offset + 4].try_into().expect("validated u32"))
}

fn read_u64(input: &[u8], offset: usize) -> u64 {
    u64::from_le_bytes(input[offset..offset + 8].try_into().expect("validated u64"))
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ProtocolError {
    message: &'static str,
}

impl ProtocolError {
    const fn new(message: &'static str) -> Self {
        Self { message }
    }
}

impl fmt::Display for ProtocolError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.message)
    }
}

