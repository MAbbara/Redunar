pub const PROTOCOL_VERSION: u16 = 7;
pub const MAX_FRAME_INTERVALS: usize = 128;
pub const MAX_REPLAY_SOURCE_WIDTH: u32 = 8_192;
pub const MAX_REPLAY_SOURCE_HEIGHT: u32 = 8_192;
pub const MAX_REPLAY_SOURCE_PIXELS: u64 = 3_840 * 2_160;
/// Accept ultrawide/portrait sources without increasing the 4K pixel budget.
/// The macroblock bound also keeps padded frames within H.264 level 5.2.
#[must_use]
pub const fn replay_source_dimensions_supported(width: u32, height: u32) -> bool {
    width > 0
        && height > 0
        && width <= MAX_REPLAY_SOURCE_WIDTH
        && height <= MAX_REPLAY_SOURCE_HEIGHT
        && (width as u64) * (height as u64) <= MAX_REPLAY_SOURCE_PIXELS
        && width.div_ceil(16) * height.div_ceil(16) <= 36_864
}
/// Shared bounded depth of Replay's asynchronous conversion/encode pipeline.
pub const REPLAY_ENCODER_PIPELINE_DEPTH: usize = 4;
/// Producer exports need one handoff beyond encoder depth so the submission
/// that recycles slot zero can arrive and release the oldest DMA-BUF.
pub const REPLAY_PRODUCER_CONTEXT_COUNT: usize = REPLAY_ENCODER_PIPELINE_DEPTH + 1;
pub const MAX_MESSAGE_BYTES: usize =
    HEADER_BYTES + FRAME_BATCH_PREFIX_BYTES + 8 * MAX_FRAME_INTERVALS;

const MAGIC: [u8; 8] = *b"RDCAP001";
const HEADER_BYTES: usize = 32;
const HELLO_BYTES: usize = 16;
const FRAME_BATCH_PREFIX_BYTES: usize = 16;
const GOODBYE_BYTES: usize = 16;
const REPLAY_SOURCE_CANDIDATE_BYTES: usize = 16 + gpu_identity::WIRE_BYTES;
const REPLAY_SOURCE_REJECTED_BYTES: usize = 8;
const REPLAY_FRAME_COPIED_BYTES: usize = 32 + gpu_identity::WIRE_BYTES;
const REPLAY_FRAME_EXPORTED_BYTES: usize = 56 + gpu_identity::WIRE_BYTES;
const REPLAY_FRAME_RELEASED_BYTES: usize = 16;
const OVERLAY_STATUS_BYTES: usize = 8;

const GPU_IDENTITY_BYTES: usize = 48;
const KIND_GPU_IDENTITY: u8 = 10;

const KIND_HELLO: u8 = 1;
const KIND_FRAME_BATCH: u8 = 2;
const KIND_GOODBYE: u8 = 3;
const KIND_REPLAY_SOURCE_CANDIDATE: u8 = 4;
const KIND_REPLAY_SOURCE_REJECTED: u8 = 5;
const KIND_REPLAY_FRAME_COPIED: u8 = 6;
const KIND_OVERLAY_STATUS: u8 = 7;
const KIND_REPLAY_FRAME_EXPORTED: u8 = 8;
const KIND_REPLAY_FRAME_RELEASED: u8 = 9;

#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct CaptureSessionId([u8; 16]);

impl CaptureSessionId {
    /// Construct a non-zero session identifier generated by the daemon.
    ///
    /// # Errors
    ///
    /// Returns [`ProtocolError`] when every byte is zero.
    pub fn new(bytes: [u8; 16]) -> Result<Self, ProtocolError> {
        if bytes == [0; 16] {
            return Err(ProtocolError::new("capture session id cannot be zero"));
        }
        Ok(Self(bytes))
    }

    #[must_use]
    pub const fn as_bytes(self) -> [u8; 16] {
        self.0
    }

    #[must_use]
    pub fn to_hex(self) -> String {
        const HEX: &[u8; 16] = b"0123456789abcdef";
        let mut encoded = String::with_capacity(32);
        for byte in self.0 {
            encoded.push(char::from(HEX[usize::from(byte >> 4)]));
            encoded.push(char::from(HEX[usize::from(byte & 0x0f)]));
        }
        encoded
    }

    /// Parse the canonical 32-character lowercase hexadecimal form used in a
    /// child process environment.
    ///
    /// # Errors
    ///
    /// Returns [`ProtocolError`] for an invalid length, non-lowercase hex, or
    /// the forbidden all-zero identifier.
    pub fn from_hex(value: &str) -> Result<Self, ProtocolError> {
        if value.len() != 32 {
            return Err(ProtocolError::new("capture session id has invalid length"));
        }
        let mut decoded = [0; 16];
        let (pairs, remainder) = value.as_bytes().as_chunks::<2>();
        debug_assert!(remainder.is_empty());
        for (index, pair) in pairs.iter().enumerate() {
            decoded[index] = (decode_hex(pair[0])? << 4) | decode_hex(pair[1])?;
        }
        Self::new(decoded)
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum CaptureApi {
    Vulkan = 1,
    OpenGl = 2,
}

impl CaptureApi {
    fn from_wire(value: u8) -> Result<Self, ProtocolError> {
        match value {
            1 => Ok(Self::Vulkan),
            2 => Ok(Self::OpenGl),
            _ => Err(ProtocolError::new("unsupported capture API")),
        }
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum GoodbyeReason {
    Normal = 1,
    ProcessExit = 2,
    ProducerError = 3,
}

impl GoodbyeReason {
    fn from_wire(value: u8) -> Result<Self, ProtocolError> {
        match value {
            1 => Ok(Self::Normal),
            2 => Ok(Self::ProcessExit),
            3 => Ok(Self::ProducerError),
            _ => Err(ProtocolError::new("unsupported capture goodbye reason")),
        }
    }
}

/// Bounded renderer failures that an in-process graphics backend can observe.
/// These describe only Redunar's optional overlay; presentation remains
/// fail-open and the game continues normally.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum OverlayFailureReason {
    RequiredVulkanFunctionsUnavailable = 1,
    GraphicsQueueUnavailable = 2,
    RendererCapacityReached = 3,
    RequiredOpenGlFunctionsUnavailable = 4,
}

impl OverlayFailureReason {
    fn from_wire(value: u8) -> Result<Self, ProtocolError> {
        match value {
            1 => Ok(Self::RequiredVulkanFunctionsUnavailable),
            2 => Ok(Self::GraphicsQueueUnavailable),
            3 => Ok(Self::RendererCapacityReached),
            4 => Ok(Self::RequiredOpenGlFunctionsUnavailable),
            _ => Err(ProtocolError::new("overlay failure reason is unsupported")),
        }
    }
}

/// Authoritative overlay state reported by an in-process graphics backend.
/// `Active` is emitted only after the backend submitted or executed overlay
/// drawing commands against the game's presentation target.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OverlayRuntimeStatus {
    Requested,
    Active,
    Error(OverlayFailureReason),
}

